    private void registerEquipment() {
        javax.swing.JTextField txtID = new javax.swing.JTextField();
        javax.swing.JTextField txtName = new javax.swing.JTextField();
        javax.swing.JTextField txtCategory = new javax.swing.JTextField();
        javax.swing.JTextField txtExtra = new javax.swing.JTextField();

        javax.swing.JRadioButton rdoIT = new javax.swing.JRadioButton("IT Equipment", true);
        javax.swing.JRadioButton rdoLab = new javax.swing.JRadioButton("Laboratory Equipment");
        javax.swing.ButtonGroup typeGroup = new javax.swing.ButtonGroup();
        typeGroup.add(rdoIT);
        typeGroup.add(rdoLab);

        javax.swing.JRadioButton rdoAvailable = new javax.swing.JRadioButton("Available", true);
        javax.swing.JRadioButton rdoBorrowed = new javax.swing.JRadioButton("Borrowed");
        javax.swing.JRadioButton rdoMaintenance = new javax.swing.JRadioButton("Under Maintenance");
        javax.swing.ButtonGroup availabilityGroup = new javax.swing.ButtonGroup();
        availabilityGroup.add(rdoAvailable);
        availabilityGroup.add(rdoBorrowed);
        availabilityGroup.add(rdoMaintenance);

        javax.swing.JLabel lblExtra = new javax.swing.JLabel("Brand:");
        rdoIT.addActionListener(e -> lblExtra.setText("Brand:"));
        rdoLab.addActionListener(e -> lblExtra.setText("Laboratory Name:"));

        javax.swing.JPanel form = new javax.swing.JPanel(new java.awt.GridLayout(0, 2, 8, 8));
        form.add(new javax.swing.JLabel("Equipment ID:"));
        form.add(txtID);
        form.add(new javax.swing.JLabel("Equipment Name:"));
        form.add(txtName);
        form.add(new javax.swing.JLabel("Category:"));
        form.add(txtCategory);
        form.add(new javax.swing.JLabel("Type:"));
        form.add(rdoIT);
        form.add(new javax.swing.JLabel(""));
        form.add(rdoLab);
        form.add(new javax.swing.JLabel("Availability:"));
        form.add(rdoAvailable);
        form.add(new javax.swing.JLabel(""));
        form.add(rdoBorrowed);
        form.add(new javax.swing.JLabel(""));
        form.add(rdoMaintenance);
        form.add(lblExtra);
        form.add(txtExtra);

        int result = javax.swing.JOptionPane.showConfirmDialog(
                this,
                form,
                "Register Equipment",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (result != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        String id = txtID.getText().trim();
        String name = txtName.getText().trim();
        String category = txtCategory.getText().trim();
        String extra = txtExtra.getText().trim();
        String availability = "Available";
        if (rdoBorrowed.isSelected()) {
            availability = "Borrowed";
        } else if (rdoMaintenance.isSelected()) {
            availability = "Under Maintenance";
        }

        if (id.isEmpty() || name.isEmpty() || category.isEmpty() || extra.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "All fields are required. Please complete the registration form.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (equipmentList.containsID(id)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Equipment ID \"" + id + "\" already exists. Duplicate IDs are not allowed.",
                    "Duplicate ID",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        Equipment newEquipment;
        if (rdoIT.isSelected()) {
            newEquipment = new ITEquipment(id, name, category, availability, extra);
        } else {
            newEquipment = new LaboratoryEquipment(id, name, category, availability, extra);
        }

        equipmentList.add(newEquipment);
        displayRecords(false);
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Equipment registered successfully.",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }

    private void displayRecords(boolean showEmptyMessage) {
        tableModel.setRowCount(0);

        if (equipmentList.isEmpty()) {
            if (showEmptyMessage) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "There are no registered equipment records.",
                        "No Records",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
            }
            return;
        }

        Equipment[] records = equipmentList.toArray();
        for (int i = 0; i < records.length; i++) {
            Equipment item = records[i];
            Object[] row = {
                item.getEquipmentID(),
                item.getEquipmentName(),
                item.getCategory(),
                item.getAvailability(),
                item.getType()
            };
            tableModel.addRow(row);
        }
    }

    private void searchEquipment() {
        String id = jTextPane1.getText().trim();

        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter an Equipment ID to search.",
                    "Search",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Equipment found = equipmentList.searchByID(id);
        if (found == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Equipment not found.",
                    "Search Result",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                found.displayInfo(),
                "Equipment Found",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }

    private void updateAvailability() {
        String id = javax.swing.JOptionPane.showInputDialog(
                this,
                "Enter Equipment ID:",
                "Update Availability",
                javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (id == null) {
            return;
        }

        id = id.trim();
        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Equipment ID is required.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Equipment found = equipmentList.searchByID(id);
        if (found == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Equipment not found.",
                    "Update Availability",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        String newAvailability = (String) javax.swing.JOptionPane.showInputDialog(
                this,
                "Select new availability for " + found.getEquipmentName() + ":",
                "Update Availability",
                javax.swing.JOptionPane.QUESTION_MESSAGE,
                null,
                AVAILABILITY_OPTIONS,
                found.getAvailability()
        );

        if (newAvailability == null) {
            return;
        }

        found.updateAvailability(newAvailability);
        displayRecords(false);
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Availability updated successfully.",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }

